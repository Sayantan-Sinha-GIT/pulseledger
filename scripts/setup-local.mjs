#!/usr/bin/env node
/**
 * Generates a unique owner password for local development and deployment.
 * The password is written only to secrets/owner-credentials.txt (gitignored).
 * The PBKDF2 hash is written to .dev.vars (gitignored) and later uploaded as a
 * Worker secret. Nothing is printed to stdout.
 */
import { pbkdf2Sync, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OWNER_EMAIL = "srimantasutapa123@gmail.com";
// Workers WebCrypto rejects PBKDF2 counts above 100,000.
const ITERATIONS = 100_000;
const root = resolve(import.meta.dirname, "..");
const devVarsPath = resolve(root, ".dev.vars");
const credentialsDir = resolve(root, "secrets");
const credentialsPath = resolve(credentialsDir, "owner-credentials.txt");

if (existsSync(devVarsPath)) {
  console.log(".dev.vars already exists; leaving the existing owner password untouched.");
  process.exit(0);
}

const password = randomBytes(24).toString("base64url");
const salt = randomBytes(16);
const hash = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
const stored = `pbkdf2-sha256$${ITERATIONS}$${salt.toString("base64")}$${hash.toString("base64")}`;

writeFileSync(
  devVarsPath,
  [
    "# Generated by scripts/setup-local.mjs. Gitignored; never commit this file.",
    `OWNER_EMAIL="${OWNER_EMAIL}"`,
    `ADMIN_PASSWORD_HASH="${stored}"`,
    'ENVIRONMENT="development"',
    "",
  ].join("\n"),
  { mode: 0o600 },
);

mkdirSync(credentialsDir, { recursive: true });
writeFileSync(
  credentialsPath,
  [
    "PulseLedger owner credentials",
    "Generated locally. This file is gitignored and must never be committed or pasted into logs.",
    "",
    `Email: ${OWNER_EMAIL}`,
    `Password: ${password}`,
    "",
    "Sign in at /admin. The same password hash is uploaded to the Worker as ADMIN_PASSWORD_HASH.",
    "",
  ].join("\n"),
  { mode: 0o600 },
);

console.log(`Created .dev.vars and ${credentialsPath}. The password was not printed.`);
